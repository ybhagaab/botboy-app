/** Per-filename write counter — tracks how many times each file has been written/appended
 *  in the current process lifetime. Helps the model understand "I'm on chunk 4 of file X"
 *  even after context trimming. Reset on process restart. Keyed by resolved path. */
const writeFileStats: Map<string, { chunks: number; overwrites: number; lastMode: string; firstWriteAt: number }> = new Map();

function isDataRoomRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value && typeof value === 'object' && !Array.isArray(value));
}

function unexpectedDataRoomFields(
  value: Record<string, unknown>,
  allowed: readonly string[],
  pathPrefix = '',
): DataRoomFailureIssueV1[] {
  return Object.keys(value)
    .filter(key => !allowed.includes(key))
    .sort()
    .map(key => dataRoomIssue({
      code: 'unsupported_field',
      path: pathPrefix ? `${pathPrefix}.${key}` : key,
      message: `${key} is not allowed here. Use only the advertised Data Room schema.`,
      expected: { kind: 'absent' },
      received: value[key],
    }));
}

function createDataRoomDatasetEnvelopeIssues(value: unknown): DataRoomFailureIssueV1[] {
  const allowedKeys = ['action', 'file', 'metric', 'regime', 'jobId', 'plan', 'ownerRequested'];
  if (!isDataRoomRecord(value)) {
    return [dataRoomIssue({
      code: 'invalid_type', path: '$', message: 'Arguments must be one object.',
      expected: { kind: 'shape', requiredKeys: ['action'], allowedKeys }, received: value,
    })];
  }
  const issues = unexpectedDataRoomFields(value, allowedKeys);
  const action = value.action;
  const actions = ['inspect_local_file', 'derive_semantic_hashes', 'create', 'status'];
  if (typeof action !== 'string' || !actions.includes(action)) {
    issues.push(dataRoomIssue({
      code: 'invalid_enum', path: 'action', message: 'action must be exactly inspect_local_file, derive_semantic_hashes, create, or status.',
      expected: { kind: 'enum', values: actions }, received: action, includeReceivedValue: true,
    }));
    return issues.slice(0, 8);
  }
  if (action !== 'inspect_local_file' && value.file !== undefined) {
    issues.push(dataRoomIssue({
      code: 'field_forbidden_for_action', path: 'file', message: `file is inspect_local_file-only and forbidden for action=${action}; a create plan names the file in its local_file source.`,
      expected: { kind: 'absent' }, received: value.file,
    }));
  }
  if (action === 'inspect_local_file') {
    const file = value.file;
    const locatorKeys = ['path', 'format', 'sheet', 'headerRow', 'nullToken'];
    if (!isDataRoomRecord(file)) {
      issues.push(dataRoomIssue({
        code: 'invalid_type', path: 'file', message: 'inspect_local_file requires file:{path[, format, sheet, headerRow, nullToken]}.',
        expected: { kind: 'shape', requiredKeys: ['path'], allowedKeys: locatorKeys }, received: file,
      }));
    } else {
      issues.push(...unexpectedDataRoomFields(file, locatorKeys, 'file'));
      if (typeof file.path !== 'string' || !file.path.trim()) issues.push(dataRoomIssue({
        code: 'required', path: 'file.path', message: 'file.path must name one local file (absolute, ~/..., or relative to BotBoy’s files workspace).',
        expected: { kind: 'range', type: 'string', minimum: 1, maximum: 4096 }, received: file.path,
      }));
      if (file.format !== undefined && !['csv', 'tsv', 'xlsx'].includes(String(file.format))) issues.push(dataRoomIssue({
        code: 'invalid_enum', path: 'file.format', message: 'file.format is optional and otherwise csv, tsv, or xlsx.',
        expected: { kind: 'enum', values: ['csv', 'tsv', 'xlsx'] }, received: file.format, includeReceivedValue: true,
      }));
      if (file.sheet !== undefined && (typeof file.sheet !== 'string' || !file.sheet)) issues.push(dataRoomIssue({
        code: 'invalid_type', path: 'file.sheet', message: 'file.sheet is an exact worksheet name.',
        expected: { kind: 'range', type: 'string', minimum: 1, maximum: 255 }, received: file.sheet,
      }));
      if (file.headerRow !== undefined && (!Number.isSafeInteger(file.headerRow) || Number(file.headerRow) < 1)) issues.push(dataRoomIssue({
        code: 'out_of_range', path: 'file.headerRow', message: 'file.headerRow is a positive 1-based row number.',
        expected: { kind: 'range', type: 'integer', minimum: 1, maximum: 50000 }, received: file.headerRow, includeReceivedValue: true,
      }));
      if (file.nullToken !== undefined && typeof file.nullToken !== 'string') issues.push(dataRoomIssue({
        code: 'invalid_type', path: 'file.nullToken', message: 'file.nullToken is optional exact text (default "").',
        expected: { kind: 'range', type: 'string', minimum: 0, maximum: 32 }, received: file.nullToken,
      }));
    }
    for (const field of ['metric', 'regime', 'jobId', 'plan', 'ownerRequested'] as const) {
      if (value[field] !== undefined) issues.push(dataRoomIssue({
        code: 'field_forbidden_for_action', path: field, message: `${field} is forbidden for action=inspect_local_file.`,
        expected: { kind: 'absent' }, received: value[field], includeReceivedValue: field === 'jobId' || field === 'ownerRequested',
      }));
    }
    return issues.slice(0, 8);
  }
  if (action === 'derive_semantic_hashes') {
    const definitions = [
      {
        field: 'metric' as const,
        fields: [
          { name: 'id', maximum: 160 },
          { name: 'version', maximum: 80 },
          { name: 'unit', maximum: 160 },
          { name: 'definition', maximum: 4000 },
        ],
      },
      {
        field: 'regime' as const,
        fields: [
          { name: 'id', maximum: 160 },
          { name: 'version', maximum: 80 },
          { name: 'definition', maximum: 4000 },
        ],
      },
    ];
    for (const definition of definitions) {
      const required = definition.fields.map(field => field.name);
      const candidate = value[definition.field];
      if (!isDataRoomRecord(candidate)) {
        issues.push(dataRoomIssue({
          code: 'invalid_type', path: definition.field,
          message: `derive_semantic_hashes requires one complete ${definition.field} definition object.`,
          expected: { kind: 'shape', requiredKeys: required, allowedKeys: required },
          received: candidate,
        }));
        continue;
      }
      const missing = required.filter(key => candidate[key] === undefined);
      if (missing.length) issues.push(dataRoomIssue({
        code: 'missing_required_fields', path: definition.field,
        message: `${definition.field} is missing required field(s): ${missing.join(', ')}.`,
        expected: { kind: 'shape', requiredKeys: required, allowedKeys: required },
        received: candidate,
      }));
      issues.push(...unexpectedDataRoomFields(candidate, required, definition.field));
      for (const field of definition.fields) {
        const fieldValue = candidate[field.name];
        if (fieldValue === undefined) continue;
        const path = `${definition.field}.${field.name}`;
        if (typeof fieldValue !== 'string') {
          issues.push(dataRoomIssue({
            code: 'invalid_type', path, message: `${path} must be a non-empty string.`,
            expected: { kind: 'range', type: 'string', minimum: 1, maximum: field.maximum }, received: fieldValue,
          }));
        } else if (!fieldValue.trim() || fieldValue.includes('\0') || fieldValue.trim().length > field.maximum) {
          issues.push(dataRoomIssue({
            code: fieldValue.includes('\0') ? 'nul_not_allowed' : fieldValue.trim() ? 'too_long' : 'required',
            path,
            message: fieldValue.includes('\0')
              ? `${path} cannot contain NUL.`
              : fieldValue.trim()
                ? `${path} exceeds ${field.maximum} characters.`
                : `${path} is required.`,
            expected: { kind: 'range', type: 'string', minimum: 1, maximum: field.maximum }, received: fieldValue,
          }));
        }
      }
    }
    for (const field of ['jobId', 'plan', 'ownerRequested'] as const) {
      if (value[field] !== undefined) issues.push(dataRoomIssue({
        code: 'field_forbidden_for_action', path: field, message: `${field} is forbidden for action=derive_semantic_hashes.`,
        expected: { kind: 'absent' }, received: value[field], includeReceivedValue: field !== 'plan',
      }));
    }
    return issues.slice(0, 8);
  }
  if (action === 'status') {
    if (typeof value.jobId !== 'string' || !/^aj_[a-f0-9]{32}$/.test(value.jobId)) {
      issues.push(dataRoomIssue({
        code: 'invalid_pattern', path: 'jobId', message: 'status requires the exact durable aj_* ID returned by create.',
        expected: { kind: 'pattern', type: 'string', pattern: '^aj_[a-f0-9]{32}$' }, received: value.jobId, includeReceivedValue: true,
      }));
    }
    if (value.plan !== undefined) issues.push(dataRoomIssue({
      code: 'field_forbidden_for_action', path: 'plan', message: 'plan is forbidden for action=status.',
      expected: { kind: 'absent' }, received: value.plan,
    }));
    if (value.ownerRequested !== undefined) issues.push(dataRoomIssue({
      code: 'field_forbidden_for_action', path: 'ownerRequested', message: 'ownerRequested is forbidden for action=status.',
      expected: { kind: 'absent' }, received: value.ownerRequested, includeReceivedValue: true,
    }));
    for (const field of ['metric', 'regime'] as const) {
      if (value[field] !== undefined) issues.push(dataRoomIssue({
        code: 'field_forbidden_for_action', path: field, message: `${field} is derive_semantic_hashes-only and forbidden for action=status.`,
        expected: { kind: 'absent' }, received: value[field],
      }));
    }
    return issues.slice(0, 8);
  }
  if (value.jobId !== undefined) issues.push(dataRoomIssue({
    code: 'field_forbidden_for_action', path: 'jobId', message: 'jobId is status-only and forbidden for action=create.',
    expected: { kind: 'absent' }, received: value.jobId, includeReceivedValue: true,
  }));
  for (const field of ['metric', 'regime'] as const) {
    if (value[field] !== undefined) issues.push(dataRoomIssue({
      code: 'field_forbidden_for_action', path: field, message: `${field} is derive_semantic_hashes-only and forbidden for action=create.`,
      expected: { kind: 'absent' }, received: value[field],
    }));
  }
  if (!isDataRoomRecord(value.plan)) {
    issues.push(dataRoomIssue({
      code: 'invalid_type', path: 'plan', message: 'create requires one fully specified plan object.',
      expected: { kind: 'shape', requiredKeys: ['version', 'mode', 'request', 'sources', 'fragments', 'terminal'], allowedKeys: ['version', 'mode', 'request', 'sources', 'fragments', 'terminal'] }, received: value.plan,
    }));
    return issues.slice(0, 8);
  }
  const plan = value.plan;
  issues.push(...unexpectedDataRoomFields(plan, ['version', 'mode', 'request', 'sources', 'fragments', 'terminal'], 'plan'));
  if (plan.version !== 1) issues.push(dataRoomIssue({
    code: 'invalid_literal', path: 'plan.version', message: 'plan.version must be the JSON number 1, not a string or compound version label.',
    expected: { kind: 'literal', value: 1 }, received: plan.version, includeReceivedValue: true,
  }));
  if (plan.mode !== 'dataset_preparation') issues.push(dataRoomIssue({
    code: 'invalid_literal', path: 'plan.mode', message: 'plan.mode must be the exact string dataset_preparation.',
    expected: { kind: 'literal', value: 'dataset_preparation' }, received: plan.mode, includeReceivedValue: true,
  }));
  if (!isDataRoomRecord(plan.request)) issues.push(dataRoomIssue({
    code: 'invalid_type', path: 'plan.request', message: 'plan.request must be the complete request object from the schema, not prose.',
    expected: { kind: 'type', type: 'object' }, received: plan.request,
  }));
  if (!Array.isArray(plan.sources) || plan.sources.length < 1 || plan.sources.length > 8) issues.push(dataRoomIssue({
    code: 'wrong_item_count', path: 'plan.sources', message: 'plan.sources must contain 1 to 8 source objects.',
    expected: { kind: 'range', type: 'array', minimum: 1, maximum: 8 }, received: plan.sources,
  }));
  if (!Array.isArray(plan.fragments) || plan.fragments.length > 32) issues.push(dataRoomIssue({
    code: 'wrong_item_count', path: 'plan.fragments', message: 'plan.fragments must be an array with at most 32 entries; use [] for a direct source.',
    expected: { kind: 'range', type: 'array', minimum: 0, maximum: 32 }, received: plan.fragments,
  }));
  if (!isDataRoomRecord(plan.terminal)) issues.push(dataRoomIssue({
    code: 'invalid_type', path: 'plan.terminal', message: 'plan.terminal must select one declared source or fragment.',
    expected: { kind: 'type', type: 'object' }, received: plan.terminal,
  }));
  return issues.slice(0, 8);
}

