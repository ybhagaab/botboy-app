/**
 * Generated versus outside (knowledge-library.md K13, amendment P2-12a): the analytics set's lessons, its manifest and the
 * presets the manifest tags etl-derived are the server's own files; everything else is an outside edit. Temp folder only.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { createGeneratedClassifier } from './knowledge-classify.js';
import { createKnowledgeHistory } from './knowledge-history.js';

let base: string;
let root: string;
beforeEach(() => {
  base = fs.realpathSync.native(fs.mkdtempSync(path.join(os.tmpdir(), 'kl-classify-')));
  root = path.join(base, 'Docs', 'BotBoy Knowledge');
  fs.mkdirSync(path.join(root, 'analytics', 'presets'), { recursive: true });
  fs.mkdirSync(path.join(root, 'analytics', 'lessons'), { recursive: true });
  fs.writeFileSync(path.join(root, 'analytics', 'manifest.json'), JSON.stringify({ files: [{ file: 'presets/shop.md', source: 'etl-derived' }, { file: 'presets/mine.md', source: 'user-dropped' }] }));
});
afterEach(() => { fs.rmSync(base, { recursive: true, force: true }); });

describe('createGeneratedClassifier', () => {
  it('calls lessons, the manifest and etl-derived presets generated, and everything else outside', () => {
    const classify = createGeneratedClassifier(() => root);
    expect(classify('analytics/lessons/basket.md')).toBe('generated');
    expect(classify('analytics/manifest.json')).toBe('generated');
    expect(classify('analytics/presets/shop.md')).toBe('generated');
    expect(classify('Analytics/Presets/Shop.md')).toBe('generated');
    expect(classify('analytics/presets/mine.md')).toBe('outside');
    expect(classify('analytics/presets/unlisted.md')).toBe('outside');
    expect(classify('analytics/notes.md')).toBe('outside');
    expect(classify('shop-data/orders.md')).toBe('outside');
  });

  it('re-reads the manifest when it changes, survives a broken or missing one, and has no answer without a root', () => {
    const classify = createGeneratedClassifier(() => root);
    expect(classify('analytics/presets/new.md')).toBe('outside');
    fs.writeFileSync(path.join(root, 'analytics', 'manifest.json'), JSON.stringify({ files: [{ file: 'presets/new.md', source: 'etl-derived' }] }));
    expect(classify('analytics/presets/new.md')).toBe('generated');
    fs.writeFileSync(path.join(root, 'analytics', 'manifest.json'), '{ not json');
    expect(classify('analytics/presets/new.md')).toBe('outside');
    fs.rmSync(path.join(root, 'analytics', 'manifest.json'));
    expect(classify('analytics/presets/new.md')).toBe('outside');
    expect(createGeneratedClassifier(() => null)('analytics/presets/new.md')).toBe('outside');
  });

  it('states the limit: the classification is by path, so a hand edit of a generated path reads as generated, and an untagged user file in presets/ stays outside', async () => {
    fs.writeFileSync(path.join(root, 'analytics', 'presets', 'shop.md'), '# Shop preset\n');
    fs.writeFileSync(path.join(root, 'analytics', 'presets', 'mine.md'), '# Mine\n');
    const history = createKnowledgeHistory({ dir: path.join(base, 'state', 'h2'), root: () => root, classify: createGeneratedClassifier(() => root) });
    await history.reconcile({ force: true });
    fs.writeFileSync(path.join(root, 'analytics', 'presets', 'shop.md'), '# Shop preset\n\nEdited by hand.\n');
    fs.writeFileSync(path.join(root, 'analytics', 'presets', 'mine.md'), '# Mine\n\nEdited by hand.\n');
    const found = await history.reconcile({ force: true });
    expect(found.map((entry) => [entry.actor, entry.files.map((file) => file.path)]).sort()).toEqual([['generated', ['analytics/presets/shop.md']], ['outside', ['analytics/presets/mine.md']]]);
  });

  it('feeds History: the server\'s own lesson file is "Generated by BotBoy", an owner file is "Edited outside BotBoy"', async () => {
    const history = createKnowledgeHistory({ dir: path.join(base, 'state', 'h'), root: () => root, classify: createGeneratedClassifier(() => root) });
    await history.reconcile({ force: true });
    fs.writeFileSync(path.join(root, 'analytics', 'lessons', 'shop.md'), '# Lessons\n');
    fs.writeFileSync(path.join(root, 'analytics', 'notes.md'), '# Notes\n');
    const found = await history.reconcile({ force: true });
    expect(found.map((entry) => [entry.actor, entry.files.map((file) => file.path)]).sort()).toEqual([['generated', ['analytics/lessons/shop.md']], ['outside', ['analytics/notes.md']]]);
    expect(found.find((entry) => entry.actor === 'generated')?.summary).toContain('Generated by BotBoy');
  });
});
